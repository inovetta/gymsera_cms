// Generates src/styles/tokens.css from design/design-tokens.json (spec §2.4).
// Run: node scripts/generate-tokens.mjs   (add --check to fail on drift)
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import path from 'node:path'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const input = path.join(root, 'design/design-tokens.json')
const output = path.join(root, 'src/styles/tokens.css')

function hexToHslTriplet(hex) {
  const n = hex.replace('#', '')
  const [r, g, b] = [0, 2, 4].map((i) => parseInt(n.slice(i, i + 2), 16) / 255)
  const max = Math.max(r, g, b)
  const min = Math.min(r, g, b)
  const l = (max + min) / 2
  const d = max - min
  let h = 0
  let s = 0
  if (d !== 0) {
    s = d / (1 - Math.abs(2 * l - 1))
    if (max === r) h = ((g - b) / d) % 6
    else if (max === g) h = (b - r) / d + 2
    else h = (r - g) / d + 4
    h = Math.round(h * 60)
    if (h < 0) h += 360
  }
  return `${h} ${Math.round(s * 100)}% ${Math.round(l * 100)}%`
}

// Token role → the CSS variable names the Tailwind config and the UI components already use.
const VAR_MAP = {
  background: 'background',
  onBackground: 'foreground',
  surface: 'card',
  onSurface: 'card-foreground',
  surfaceVariant: 'muted',
  onSurfaceVariant: 'muted-foreground',
  border: 'border',
  primary: 'primary',
  onPrimary: 'primary-foreground',
  success: 'success',
  onSuccess: 'success-foreground',
  warning: 'warning',
  onWarning: 'warning-foreground',
  danger: 'destructive',
  onDanger: 'destructive-foreground',
  info: 'info',
  onInfo: 'info-foreground',
  brand: 'brand',
  roleOwner: 'role-owner',
  roleManager: 'role-manager',
  roleDesk: 'role-desk',
  roleTrainer: 'role-trainer',
  onRole: 'on-role',
  sidebar: 'sidebar',
  onSidebar: 'sidebar-foreground',
  sidebarAccent: 'sidebar-accent',
}

// Variables the components expect that are the same role under a second name.
const ALIASES = {
  popover: 'surface',
  'popover-foreground': 'onSurface',
  secondary: 'surfaceVariant',
  'secondary-foreground': 'onSurface',
  accent: 'surfaceVariant',
  'accent-foreground': 'onSurface',
  input: 'border',
  ring: 'primary',
  'sidebar-accent-foreground': 'onSidebar',
  'sidebar-border': 'sidebarAccent',
}

export function buildCss(tokens) {
  const block = (mode) => {
    const lines = []
    for (const [role, name] of Object.entries(VAR_MAP)) {
      lines.push(`  --${name}: ${hexToHslTriplet(tokens.color[role][mode])};`)
    }
    for (const [name, role] of Object.entries(ALIASES)) {
      lines.push(`  --${name}: ${hexToHslTriplet(tokens.color[role][mode])};`)
    }
    return lines.join('\n')
  }
  const shared = [
    ...tokens.space.map((v, i) => `  --space-${i}: ${v}px;`),
    ...Object.entries(tokens.radius).map(([k, v]) => `  --radius-${k}: ${v}px;`),
    `  --radius: ${tokens.radius.lg}px;`,
    ...Object.entries(tokens.elevation).map(([k, v]) => `  --elevation-${k}: ${v};`),
    ...Object.entries(tokens.motion).map(([k, v]) => `  --motion-${k}: ${v}ms;`),
  ].join('\n')
  return `/* GENERATED by scripts/generate-tokens.mjs from design/design-tokens.json. Do not edit by hand. */
:root {
${block('light')}
${shared}
}

.dark {
${block('dark')}
}
`
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const css = buildCss(JSON.parse(readFileSync(input, 'utf8')))
  if (process.argv.includes('--check')) {
    if (readFileSync(output, 'utf8') !== css) {
      console.error('src/styles/tokens.css is out of date. Run: node scripts/generate-tokens.mjs')
      process.exit(1)
    }
  } else {
    writeFileSync(output, css)
    console.log(`wrote ${path.relative(root, output)}`)
  }
}
